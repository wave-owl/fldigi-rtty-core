#!/usr/bin/env python3
"""Regenerate the TX golden data in tests/golden/tx from a wave-owl checkout.

Usage (with the wave-owl virtualenv active):

    python tests/golden/make_tx_golden.py /path/to/wave-owl [out_dir]

For each fldigi 4.2.13 reference vector ``src/modes/rtty/vectors/<name>.{wav,json}`` of
wave-owl (headless fldigi TX, 8000 Hz, carrier 1500 Hz = mark 1585 Hz / space 1415 Hz,
shaped keying, txlevel -12 dB, 16-bit PCM):

* ``<name>.s16`` -- the WAV samples as little-endian int16 raw data (unchanged).
* ``<name>.codes`` -- ``#`` comment lines, one line ``rate mark space baud stop`` and the
  5-bit codes of the whole transmission as decimal numbers, framed with wave-owl
  ``src.modes.rtty.ita2.TxFramer().frame(text)`` (fldigi ``rtty::tx_process``,
  rtty.cxx:1173-1412). The flush (rtty.cxx:1032-1056) follows the last code.
"""

import hashlib
import json
import os
import sys

import numpy as np
import soundfile as sf

VECTORS = ("rtty_cq", "rtty_cq_stop1", "rtty_cq_stop2", "rtty_50bd_long")
#: fldigi RTTYBAUD / RTTYSTOP indices (configuration.h:444-460, rtty.cxx:97).
BAUD = {0: 45.0, 1: 45.45, 2: 50.0, 3: 56.0, 4: 75.0, 5: 100.0}
STOP = {0: 1.0, 1: 1.5, 2: 2.0}
SHIFT = {3: 170.0}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    wave_owl = os.path.abspath(sys.argv[1])
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "tx"))
    sys.path.insert(0, wave_owl)
    from src.modes.rtty.ita2 import TxFramer

    os.makedirs(out, exist_ok=True)
    vec_dir = os.path.join(wave_owl, "src", "modes", "rtty", "vectors")
    for name in VECTORS:
        with open(os.path.join(vec_dir, name + ".json")) as f:
            meta = json.load(f)
        wav = os.path.join(vec_dir, name + ".wav")
        with open(wav, "rb") as f:
            if hashlib.sha256(f.read()).hexdigest() != meta["sha256"]:
                sys.exit("sha256 mismatch for %s" % wav)
        pcm, rate = sf.read(wav, dtype="int16")
        assert rate == 8000 and pcm.ndim == 1, name
        pcm.astype("<i2").tofile(os.path.join(out, name + ".s16"))
        gen = meta["generator"]
        cfg = gen["config_overrides"]
        text = gen["environment"]["FLDIGI_BENCH_TX_TEXT"]
        carrier = meta["fldigi_mode"]["carrier_hz"]
        shift = SHIFT[cfg["RTTYSHIFT"]]
        baud, stop = BAUD[cfg["RTTYBAUD"]], STOP[cfg["RTTYSTOP"]]
        codes = TxFramer().frame(text)
        with open(os.path.join(out, name + ".codes"), "w") as f:
            f.write("# %s carrier_hz=%d txlevel_db=%.1f samples=%d\n"
                    % (name, carrier, meta["fldigi_mode"]["txlevel_db"], len(pcm)))
            f.write("# text: %s\n" % json.dumps(text))
            f.write("# generated by tests/golden/make_tx_golden.py with wave-owl "
                    "src.modes.rtty.ita2.TxFramer().frame(text)\n")
            f.write("%d %.2f %.2f %.2f %.1f\n" % (rate, carrier + shift / 2, carrier - shift / 2,
                                                  baud, stop))
            f.write(" ".join(str(c) for c in codes) + "\n")
        print("%s: %d samples, %d codes" % (name, len(pcm), len(codes)))


if __name__ == "__main__":
    main()
